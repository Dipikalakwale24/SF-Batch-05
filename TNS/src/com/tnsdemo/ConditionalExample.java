package com.tnsdemo;

public class ConditionalExample {

	public static void main(String[] args) {
		int number = 15;

        if (number > 0) {
            System.out.println("Number is Positive");
        } else if (number < 0) {
            System.out.println("Number is Negative");
        } else {
            System.out.println("Number is Zero");
        }

	}

}
